#!/usr/bin/env bash
# setup-proxy.sh — SOCKS5 proxy on a VPS that egresses ONLY via the VPN tunnel.
#
# Uses dante-server (danted): the "external" interface is pinned to the tunnel
# device, so if the tunnel is down, proxied connections FAIL instead of leaking
# from the VPS's real IP (kill-switch semantics — same idea as the HMA client's
# killswitch.dfl).
#
# Access model (pick one):
#   default   : proxy listens on 127.0.0.1:1080 only. Reach it via SSH:
#                 ssh -N -L 1080:127.0.0.1:1080 user@VPS
#   --public  : also listens on the VPS public IP, firewalled to --allow CIDR.
#               Only do this with a firewall; an open proxy gets abused in minutes.
#
# Usage:
#   sudo ./setup-proxy.sh                       # localhost-only, prompts for password
#   sudo ./setup-proxy.sh --user prox --password 'S3cret'
#   sudo ./setup-proxy.sh --public --allow 203.0.113.7/32
#   sudo TUNIF=ovpn-dco ./setup-proxy.sh        # force tunnel interface name
set -euo pipefail

USER_NAME="danteproxy"
PUBLIC=0
ALLOW=""
HTTP_PORT=""
while [ $# -gt 0 ]; do
  case "$1" in
    --user)     USER_NAME="$2"; shift 2 ;;
    --password) PROXY_PASS="$2"; shift 2 ;;
    --public)   PUBLIC=1; shift ;;
    --allow)    ALLOW="$2"; shift 2 ;;
    --http)     HTTP_PORT="$2"; shift 2 ;;
    *) echo "unknown arg: $1" >&2; exit 2 ;;
  esac
done

[ "$(id -u)" = 0 ] || { echo "run with sudo"; exit 1; }
command -v apt-get >/dev/null || { echo "Debian/Ubuntu only (apt)"; exit 1; }

echo "== installing dante-server"
export DEBIAN_FRONTEND=noninteractive
apt-get update -qq
apt-get install -y -qq dante-server

# ---- interfaces -----------------------------------------------------------
TUNIF="${TUNIF:-}"
if [ -z "$TUNIF" ]; then
  # first tun/utun/ppp device; script exits if none yet (bring the VPN up first,
  # or set TUNIF=... explicitly)
  for f in /sys/class/net/*; do
    b=$(basename "$f")
    case "$b" in tun*|utun*|ppp*|wg*|ovpn*) TUNIF="$b"; break ;; esac
  done
fi
if [ -z "$TUNIF" ]; then
  echo "ERROR: no tunnel interface found (tun*/wg*/ppp*)." >&2
  echo "Bring the VPN up first, or run:  sudo TUNIF=<iface> $0 ..." >&2
  exit 1
fi
echo "tunnel interface: $TUNIF"

PUBIF=$(ip -4 route show default | awk '{print $5; exit}')
PUBIP=$(ip -4 -o addr show dev "$PUBIF" scope global | awk '{split($4,a,"/"); print a[1]; exit}')
echo "public interface: $PUBIF ($PUBIP)"

# ---- auth user ------------------------------------------------------------
if ! id "$USER_NAME" >/dev/null 2>&1; then
  useradd -r -M -s /usr/sbin/nologin "$USER_NAME"
fi
if [ -z "${PROXY_PASS:-}" ]; then
  read -rs -p "SOCKS5 password for '$USER_NAME': " PROXY_PASS; echo
fi
printf '%s:%s\n' "$USER_NAME" "$PROXY_PASS" | chpasswd
echo "auth user: $USER_NAME"

# ---- danted.conf ----------------------------------------------------------
cat > /etc/danted.conf <<EOF
# generated by setup-proxy.sh
logoutput: syslog
internal: 127.0.0.1 port = 1080
external: $TUNIF
method: username
user.privileged: root
user.notprivileged: $USER_NAME
connecttimeout: 30
iotimeout: 120

client pass {
    from: 127.0.0.1/32 to: 0.0.0.0/0
    log: error
}
socks pass {
    from: 127.0.0.1/32 to: 0.0.0.0/0
    protocol: tcp udp
    method: username
    log: error
}
EOF

if [ "$PUBLIC" = 1 ]; then
  [ -n "$ALLOW" ] || { echo "--public requires --allow <clientCIDR>"; exit 1; }
  cat >> /etc/danted.conf <<EOF

# public listener — restricted to $ALLOW
internal: $PUBIP port = 1080
client pass {
    from: $ALLOW to: 0.0.0.0/0
    log: error
}
socks pass {
    from: $ALLOW to: 0.0.0.0/0
    protocol: tcp udp
    method: username
    log: error
}
EOF
  # default-deny on the proxy port for everyone else
  iptables -C INPUT -p tcp --dport 1080 -s "$ALLOW" -j ACCEPT 2>/dev/null || \
    iptables -I INPUT -p tcp --dport 1080 -s "$ALLOW" -j ACCEPT
  iptables -C INPUT -p tcp --dport 1080 ! -s "$ALLOW" -j DROP 2>/dev/null || \
    iptables -I INPUT -p tcp --dport 1080 ! -s "$ALLOW" -j DROP
fi

# ---- optional HTTP proxy (tinyproxy chained through the SOCKS5) -----------
# Many apps only support HTTP proxies; tinyproxy forwards them into dante,
# which still pins egress to the tunnel interface.
HTTP_PORT="${HTTP_PORT:-}"
if [ -n "$HTTP_PORT" ]; then
  apt-get install -y -qq tinyproxy
  [ -f /etc/tinyproxy/tinyproxy.conf ] && \
    cp -n /etc/tinyproxy/tinyproxy.conf /etc/tinyproxy/tinyproxy.conf.orig 2>/dev/null || true
  cat > /etc/tinyproxy/tinyproxy.conf <<EOF
Port $HTTP_PORT
Listen 127.0.0.1
Timeout 600
LogLevel Error
Upstream socks5 127.0.0.1:1080 "$USER_NAME" "$PROXY_PASS"
EOF
  systemctl enable --now tinyproxy
  systemctl restart tinyproxy
  echo "HTTP proxy on 127.0.0.1:$HTTP_PORT (chain: tinyproxy → dante → tunnel)"
fi

systemctl enable --now danted
sleep 1
systemctl --no-pager --lines=5 status danted || true

echo
echo "== done. SOCKS5 $USER_NAME@$( [ "$PUBLIC" = 1 ] && echo "$PUBIP" || echo 127.0.0.1 ):1080 (egress: $TUNIF only)"
[ -n "$HTTP_PORT" ] && echo "== HTTP proxy on 127.0.0.1:$HTTP_PORT"
echo "usage from apps on this VM:"
echo "  SOCKS5  : 127.0.0.1:1080  (user: $USER_NAME)"
[ -n "$HTTP_PORT" ] && echo "  HTTP    : 127.0.0.1:$HTTP_PORT"
echo "verify :  curl --socks5-hostname 127.0.0.1:1080 -u $USER_NAME:<pass> https://ip-info.ff.avast.com/v2/info"
